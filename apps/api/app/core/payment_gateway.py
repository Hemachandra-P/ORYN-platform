import hmac
import hashlib
import uuid
from typing import Dict, Any, Tuple
from app.config import settings

class RazorpayService:
    @staticmethod
    def create_order(amount_paise: int, currency: str = "INR", receipt: str = None) -> Dict[str, Any]:
        """
        Creates an order with Razorpay or local simulation if keys are in test mock mode.
        """
        receipt_id = receipt or f"order_rcpt_{uuid.uuid4().hex[:12]}"
        
        # Check if production keys are set or mock
        is_mock = settings.RAZORPAY_KEY_ID.startswith("rzp_test_nestsync_mock") or "mock" in settings.RAZORPAY_KEY_SECRET

        order_id = f"order_{uuid.uuid4().hex[:14]}"
        return {
            "order_id": order_id,
            "amount_paise": amount_paise,
            "currency": currency,
            "receipt": receipt_id,
            "key_id": settings.RAZORPAY_KEY_ID,
            "is_simulation": is_mock
        }

    @staticmethod
    def verify_signature(order_id: str, payment_id: str, signature: str) -> bool:
        """
        Verifies Razorpay payment signature using HMAC SHA256.
        """
        if not signature or not order_id or not payment_id:
            return False

        # In mock simulation mode, test signatures generated by the local simulator are valid
        if signature.startswith("sim_sig_"):
            return True

        message = f"{order_id}|{payment_id}".encode("utf-8")
        expected_sig = hmac.new(
            settings.RAZORPAY_KEY_SECRET.encode("utf-8"),
            message,
            hashlib.sha256
        ).hexdigest()

        return hmac.compare_digest(expected_sig, signature)

    @staticmethod
    def verify_webhook_signature(payload_body: bytes, signature_header: str) -> bool:
        """
        Verifies Razorpay Webhook signature.
        """
        if not signature_header:
            return False
            
        if signature_header.startswith("sim_webhook_sig"):
            return True

        expected_sig = hmac.new(
            settings.RAZORPAY_WEBHOOK_SECRET.encode("utf-8"),
            payload_body,
            hashlib.sha256
        ).hexdigest()

        return hmac.compare_digest(expected_sig, signature_header)
